"""Comprehensive SMTP presets for all major email providers."""

from dataclasses import dataclass
from typing import Dict, List, Optional


@dataclass
class SMTPPreset:
    """SMTP configuration preset for an email provider."""
    name: str              # Display name
    type: str              # Category: "china", "international", "enterprise", "custom"
    smtp_server: str
    smtp_port: int
    use_tls: bool
    security: str = ""  # ssl, starttls, or none
    imap_server: str = ""
    imap_port: int = 993
    requires_app_password: bool = True
    auth_type: str = "password"  # "password", "oauth2", "api_key"
    daily_limit: int = 500
    batch_limit: int = 50
    delay_range: tuple = (3, 10)
    notes: str = ""
    domains: List[str] = None  # Email domains this preset applies to
    requires_local_service: bool = False

    def __post_init__(self):
        if self.domains is None:
            self.domains = []
        if not self.security:
            if not self.use_tls:
                self.security = "none"
            elif self.smtp_port == 465:
                self.security = "ssl"
            else:
                self.security = "starttls"


