def get_preset(key: str) -> Optional[SMTPPreset]:
    """Get SMTP preset by key."""
    return SMTP_PRESETS.get(key)


def get_presets_by_type(type_filter: str) -> List[SMTPPreset]:
    """Get all presets of a specific type."""
    return [p for p in SMTP_PRESETS.values() if p.type == type_filter]


def get_preset_for_email(email: str) -> Optional[SMTPPreset]:
    """Auto-detect best preset based on email domain."""
    domain = email.split("@")[-1].lower()
    for preset in SMTP_PRESETS.values():
        if preset.domains and domain in preset.domains:
            return preset
    return None


def get_all_presets() -> Dict[str, SMTPPreset]:
    """Get all presets."""
    return SMTP_PRESETS


